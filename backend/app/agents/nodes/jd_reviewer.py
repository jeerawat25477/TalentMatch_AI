"""JD Reviewer — ตรวจว่าประกาศรับสมัครงานนี้ใช้ **คัดกรองเรซูเม่** ได้ดีแค่ไหน ก่อน HR กด "วิเคราะห์".

⚠️ **ไม่ใช่โหนดในกราฟ** ถึงจะอยู่ในโฟลเดอร์ nodes/ ก็ตาม — เป็นฟังก์ชันเดี่ยวที่ router
เรียกตรง ๆ จึงรับ `str` ไม่ใช่ HRSystemState และไม่ถูก export ใน nodes/__init__.py
(ไฟล์นั้นรวมเฉพาะ 7 โหนดของกราฟตามลำดับการรัน) การเสียบเข้ากราฟจะกระทบ pipeline
ที่ทดสอบ e2e ผ่านแล้ว โดยไม่ได้อะไรเพิ่ม เพราะงานนี้ต้องรัน *ก่อน* มีตำแหน่งงานในระบบด้วยซ้ำ

**ตรวจเพื่อคัดกรอง ไม่ใช่เพื่อโพสต์** (เปลี่ยน 2026-09-29) เดิม prompt ตั้งบทเป็นที่ปรึกษา "ก่อนนำไป
โพสต์จริง" และสั่งให้หาช่วงเงินเดือน/สถานที่ทำงาน/รูปแบบไฮบริด HR ได้คำแนะนำแบบประกาศ JobsDB
ซึ่งไม่มีผลกับคะแนนผู้สมัครสักคะแนน ในระบบนี้ประกาศถูกใช้ *สกัดเกณฑ์คัดกรอง* จึงตรวจสิ่งที่ทำให้
คัดกรองพลาด: เกณฑ์ที่วัดจากเรซูเม่ไม่ได้, ทักษะกว้างเกิน, โครงสร้างต้องมี/อยากได้ไม่ชัด,
ข้อบังคับเยอะเกิน · เรื่องที่เป็นของการโพสต์เหลือเป็น posting_tips ความสำคัญต่ำสุด

**ไม่ตรวจอคติที่นี่** — `bias_auditor.audit_jd` + กฎตายตัว (`bias_rules.py`) ตรวจตอนกด "วิเคราะห์"
อยู่แล้วและแม่นกว่า ถ้าตรวจสองที่ HR จะเห็นผลสองชุดที่พูดไม่ตรงกัน

prompt อธิบายวิธีให้คะแนนจริงให้ AI ฟัง ด้วยน้ำหนักจาก `matcher.py` ไม่เขียนเลขซ้ำ —
คำแนะนำจึงอิงกลไกของระบบนี้ ไม่ใช่คำแนะนำการเขียนประกาศทั่วไป
"""
from app.agents.llm import structured_invoke_once
from app.agents.models import JDReview
from app.agents.nodes.matcher import PREFERRED_WEIGHT, REQUIRED_WEIGHT

# ตัดประกาศที่ยาวผิดปกติกันเปลือง token (แนวเดียวกับ _MAX_JD_CHARS ของ bias_auditor)
# กว้างกว่าของ auditor เพราะที่นี่ HR อาจวางประกาศเต็มฉบับรวมสวัสดิการมาทั้งก้อน
MAX_JD_CHARS = 8000

PROMPT = """คุณคือผู้เชี่ยวชาญระบบคัดกรองเรซูเม่ กำลังช่วย HR ตรวจว่า "ประกาศรับสมัครงาน" ฉบับนี้
ถ้าเอาไปใช้คัดกรองเรซูเม่อัตโนมัติ จะได้ผลที่ถูกต้องแค่ไหน · ยังไม่มีผู้สมัครในขั้นนี้

ระบบคัดกรองทำงานแบบนี้ (ใช้เป็นหลักในการให้คำแนะนำ):
- อ่านประกาศแล้วแยกทักษะเป็นสองกลุ่ม "ต้องมี" กับ "อยากได้" จากหัวข้อในประกาศ
- เทียบกับทักษะที่เขียนในเรซูเม่ของผู้สมัครทีละข้อ แบบตรงชื่อ (ไม่ใช่การตีความ)
- คะแนน = ต้องมี {required_weight}% + อยากได้ {preferred_weight}% ตามสัดส่วนข้อที่ตรง
- **ทุกข้อในกลุ่ม "ต้องมี" คือข้อบังคับ** · ถ้ามีตัวใดตัวหนึ่งก็พอ ต้องเขียนด้วยคำว่า "หรือ"
- สิ่งที่ไม่ใช่ทักษะที่เขียนลงเรซูเม่ได้ ระบบตัดทิ้ง ไม่นำมาคิดคะแนน

ตรวจ 6 ด้าน:

1. scope_assessment — ขอบเขตของตำแหน่ง
   - "too_broad" = ยัดหลายบทบาทมารวมกัน จนข้อบังคับเยอะและแทบไม่มีใครผ่าน
   - "too_narrow" = เจาะจงจนเหลือผู้สมัครน้อยเกินไปโดยไม่จำเป็น
   - "balanced" = พอดี
   พร้อม scope_comment อธิบายเหตุผลสั้น ๆ

2. unmeasurable — เกณฑ์ที่ดูจากเรซูเม่ไม่ได้ เช่น "ขยัน อดทน", "มีใจรักบริการ", "ทำงานเป็นทีมได้"
   ไม่มีใครเขียนแบบนี้ในเรซูเม่ ระบบจึงตัดทิ้งหรือนับว่าไม่มีทุกคน
   แนะนำให้ย้ายไปถามตอนสัมภาษณ์ หรือเขียนใหม่เป็นสิ่งที่เห็นได้ในเรซูเม่
   **ดูเฉพาะส่วนคุณสมบัติ** — ประโยคในส่วนหน้าที่ความรับผิดชอบ ("ทำงานร่วมกับทีม Designer")
   ไม่ใช่เกณฑ์คัดกรอง ระบบไม่ได้เอาไปให้คะแนนอยู่แล้ว ห้ามนับเป็นข้อนี้

3. vague_skills — ทักษะที่กว้างเกินจนจับคู่กับเรซูเม่ไม่ได้ เช่น "เก่งคอมพิวเตอร์", "รู้เรื่อง IT"
   แนะนำให้ระบุเป็นชื่อเครื่องมือหรือทักษะที่เจาะจง เช่น "Excel, Word"

4. structure_issues — โครงสร้างที่ทำให้ระบบอ่านผิด เช่น
   - ไม่มีหัวข้อแยก "ต้องมี" กับ "อยากได้" ระบบจะเดาว่าทุกข้อเป็นข้อบังคับ
   - ตัวเลือกเขียนด้วยจุลภาค ("React, Vue") ไม่ชัดว่าต้องมีทั้งคู่หรือตัวใดตัวหนึ่ง
   - หน้าที่ความรับผิดชอบปนอยู่ในรายการคุณสมบัติ

5. must_have_review — ทักษะที่อยู่ในกลุ่ม "ต้องมี" แต่ควรทบทวน เช่น ควรเป็น "อยากได้" มากกว่า
   เข้มเกินระดับตำแหน่ง หรือเป็นวิธีทำงานที่คนไม่ค่อยเขียนลงเรซูเม่ (เช่น Agile, Scrum)
   จนทำให้ผู้สมัครที่ทำงานได้จริงได้คะแนนต่ำทั้งกระดาน

6. posting_tips — **ความสำคัญต่ำสุด** เฉพาะกรณีจะนำประกาศนี้ไปโพสต์บนเว็บหางานภายนอก:
   ข้อมูลที่ผู้สมัครอยากรู้แต่ยังขาด เช่น ช่วงเงินเดือน สถานที่ทำงาน รูปแบบการทำงาน
   สั้น ๆ ไม่เกิน 3 ข้อ · เรื่องพวกนี้ไม่มีผลกับการคัดกรอง ห้ามนำไปพูดใน overall_comment

แล้วสรุป overall_comment หนึ่งย่อหน้า: ถ้าจะให้คัดกรองแม่นขึ้น ควรแก้อะไรก่อน

กติกาสำคัญ:
- ถ้าประกาศเขียนดีอยู่แล้วในด้านไหน ให้คืนรายการว่างของด้านนั้น **ห้ามปั้นปัญหาขึ้นมา**
  เพื่อให้ดูเหมือนทำงาน — คำเตือนที่ไม่จริงจะทำให้ HR เลิกเชื่อคำเตือนทั้งหมด
- phrase ใน unmeasurable / vague_skills ต้องยกมาจากประกาศจริงเท่านั้น ห้ามแต่งขึ้นเอง
- **ไม่ต้องตรวจเรื่องอคติ** (เพศ อายุ ศาสนา ฯลฯ) ระบบมีตัวตรวจแยกต่างหากตอนกดวิเคราะห์
- ตอบเป็นภาษาไทย

ประกาศรับสมัครงาน:
{raw_jd}"""


def review_jd(raw_text: str) -> JDReview:
    """ตรวจประกาศแล้วคืนคำแนะนำ — เรียก LLM ครั้งเดียว ไม่ retry.

    ใช้ structured_invoke_once เพราะ HR นั่งรอผลอยู่หน้าจอ: ถ้าโควตารายวันหมด
    การ retry จะหน่วงเป็นนาทีแล้วก็ล้มอยู่ดี บอกให้รู้เร็ว ๆ มีประโยชน์กว่า
    """
    return structured_invoke_once(
        PROMPT.format(
            raw_jd=raw_text[:MAX_JD_CHARS],
            required_weight=REQUIRED_WEIGHT,
            preferred_weight=PREFERRED_WEIGHT,
        ),
        JDReview,
    )
