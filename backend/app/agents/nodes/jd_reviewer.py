"""JD Reviewer — ตรวจประกาศรับสมัครงาน "ก่อนโพสต์" แล้วให้คำแนะนำกับ HR.

⚠️ **ไม่ใช่โหนดในกราฟ** ถึงจะอยู่ในโฟลเดอร์ nodes/ ก็ตาม — เป็นฟังก์ชันเดี่ยวที่ router
เรียกตรง ๆ จึงรับ `str` ไม่ใช่ HRSystemState และไม่ถูก export ใน nodes/__init__.py
(ไฟล์นั้นรวมเฉพาะ 7 โหนดของกราฟตามลำดับการรัน) การเสียบเข้ากราฟจะกระทบ pipeline
ที่ทดสอบ e2e ผ่านแล้ว โดยไม่ได้อะไรเพิ่ม เพราะงานนี้ต้องรัน *ก่อน* มีตำแหน่งงานในระบบด้วยซ้ำ

ต่างจากเพื่อนบ้านสองตัวที่ดู JD เหมือนกัน:
- `jd_analyzer` *สกัด* JD เป็น JobRequirement เพื่อเอาไปให้คะแนนผู้สมัคร — ไม่วิจารณ์อะไร
  และ prompt ของมันโยนเกณฑ์ที่ไม่ใช่ทักษะทิ้งตั้งแต่ต้น
- `bias_auditor` ตรวจอคติจาก raw_jd ก็จริง แต่รันตอน *ประเมินผู้สมัครแต่ละคน* เท่านั้น
  (ต้องมี evaluations + parsed_resumes) ตอน HR ร่างประกาศยังไม่มีผู้สมัครสักคน
  และมันดูแค่ 5 กลุ่มคุ้มครอง (เพศ อายุ เชื้อชาติ ศาสนา สถาบัน)

ตัวนี้จึงกว้างกว่า: ขอบเขตของตำแหน่ง, ความสมเหตุสมผลของ must-have, ข้อมูลที่ขาด
และถ้อยคำกีดกันแบบอื่นที่ไม่ได้อยู่ใน 5 กลุ่มนั้น
"""
from app.agents.llm import structured_invoke_once
from app.agents.models import JDReview

# ตัดประกาศที่ยาวผิดปกติกันเปลือง token (แนวเดียวกับ _MAX_JD_CHARS ของ bias_auditor)
# กว้างกว่าของ auditor เพราะที่นี่ HR อาจวางประกาศเต็มฉบับรวมสวัสดิการมาทั้งก้อน
MAX_JD_CHARS = 8000

PROMPT = """คุณคือที่ปรึกษาด้านการสรรหาบุคลากร กำลังช่วย HR ตรวจ "ร่างประกาศรับสมัครงาน"
ก่อนนำไปโพสต์จริง งานของคุณคือวิจารณ์ตัวประกาศเพื่อให้แก้ให้ดีขึ้น
**ไม่ใช่**การสกัดข้อมูลออกมาเป็นตาราง และยังไม่มีผู้สมัครให้ประเมินในขั้นนี้

ประเมิน 5 ด้าน:

1. scope_assessment — ขอบเขตของตำแหน่ง
   - "too_broad" = ยัดหลายบทบาทมารวมกันจนหาคนเดียวที่ทำได้ทั้งหมดแทบไม่ได้
   - "too_narrow" = เจาะจงจนเหลือผู้สมัครน้อยเกินไปโดยไม่จำเป็น
   - "balanced" = พอดี
   พร้อม scope_comment อธิบายเหตุผลสั้น ๆ

2. bias_flags — ถ้อยคำที่กีดกันผู้สมัครโดยไม่จำเป็น ยกข้อความจากประกาศมาตรง ๆ
   ครอบคลุมทั้ง เพศ อายุ เชื้อชาติ ศาสนา สถาบันการศึกษา สถานภาพสมรส รูปลักษณ์
   และถ้อยคำที่กีดกันทางอ้อม เช่น เรียกร้องวัฒนธรรมการทำงานที่ตัดคนบางกลุ่มออก
   ("รับได้เฉพาะคนที่ทำงานดึกได้ทุกวัน") หรือคำที่สื่อภาพจำทางเพศ
   แต่ละข้อบอกด้วยว่าควรแก้เป็นอะไร

3. must_have_review — ทักษะที่ประกาศบอกว่า "ต้องมี" แต่ควรทบทวน
   เช่น ควรเป็น "มีก็ดี" มากกว่า, เข้มเกินระดับตำแหน่ง,
   หรือกำหนดจำนวนปีประสบการณ์เกินจริงเมื่อเทียบกับอายุของเทคโนโลยีนั้น

4. missing_info — ข้อมูลที่ประกาศที่ดีควรมีแต่ฉบับนี้ยังขาด
   เช่น ช่วงเงินเดือน สถานที่ทำงาน รูปแบบการทำงาน (ออนไซต์/ไฮบริด/รีโมต)
   ขอบเขตความรับผิดชอบ ทีมที่จะสังกัด เส้นทางเติบโต

5. overall_comment — สรุปภาพรวมหนึ่งย่อหน้าให้ HR อ่านแล้วรู้ว่าควรแก้อะไรก่อน

กติกาสำคัญ:
- ถ้าประกาศเขียนดีอยู่แล้วในด้านไหน ให้คืนรายการว่างของด้านนั้น **ห้ามปั้นปัญหาขึ้นมา**
  เพื่อให้ดูเหมือนทำงาน — คำเตือนที่ไม่จริงจะทำให้ HR เลิกเชื่อคำเตือนทั้งหมด
- ยกข้อความใน bias_flags.phrase มาจากประกาศจริงเท่านั้น ห้ามแต่งขึ้นเอง
- ตอบเป็นภาษาไทย

ร่างประกาศรับสมัครงาน:
{raw_jd}"""


def review_jd(raw_text: str) -> JDReview:
    """ตรวจร่างประกาศแล้วคืนคำแนะนำ — เรียก LLM ครั้งเดียว ไม่ retry.

    ใช้ structured_invoke_once เพราะ HR นั่งรอผลอยู่หน้าจอ: ถ้าโควตารายวันหมด
    การ retry จะหน่วงเป็นนาทีแล้วก็ล้มอยู่ดี บอกให้รู้เร็ว ๆ มีประโยชน์กว่า
    """
    return structured_invoke_once(
        PROMPT.format(raw_jd=raw_text[:MAX_JD_CHARS]), JDReview
    )
